const DICT: Record<Lang, Record<string, string>> = { en: {}, si: SI, ta: TA };

/** t("English text {x}", { x: 3 }). Unknown key: the English text. */
export function makeT(lang: Lang): (en: string, vars?: Record<string, string | number>) => string {
  const d = DICT[lang] ?? {};
  return (en, vars) => {
    let s = d[en] ?? en;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
export const isLang = (v: string): v is Lang => v === "en" || v === "si" || v === "ta";
