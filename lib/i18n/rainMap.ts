const DICTS: Record<Locale, Partial<D>> = { en, si, ta };
export type RmKey = K;
export type RM = (key: K, vars?: Record<string, string | number>) => string;
export function rmFor(lang: Locale): RM {
  const d = DICTS[lang] ?? en;
  return (key, vars) => {
    const s = d[key] ?? en[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}
