export type TT = (key: TKey, vars?: Record<string, string | number>) => string;
export function ttFor(lang: Locale): TT {
  const d = DICTS[lang];
  return (key, vars) => {
    const s = d[key] ?? en[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}
