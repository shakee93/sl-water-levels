#!/usr/bin/env node
// Which town pages get the embedded flood test map: towns whose point sits inside the calibrated picture (public/flood3d/level.webp),
// i.e. where the surrounding ground is not flagged "not covered" (blue channel bit 32) and is not just river. Writes lib/flood3dCoverage.ts.
// Re-run after prep.py rewrites level.webp or lib/places.ts changes:  node scripts/flood3d/town-coverage.mjs
// ("sharp" comes with Next.js; nothing is added to package.json.)
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const sharp = require("sharp");
const acc = JSON.parse(readFileSync("public/flood3d/accuracy.json", "utf8")).png;
const { data, info } = await sharp("public/flood3d/level.webp").ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const W = info.width, H = info.height, ch = info.channels;
// places: read the table the same way the site does (lib/places.ts is TypeScript, so strip it with Node's type stripping)
const { PLACES } = await import("../../lib/places.ts");
const R = 5; // +-5 cells (about 150 m)
const out = [];
for (const p of PLACES) {
  const ix = Math.floor((p.lon - acc.west) / acc.deg), iy = Math.floor((acc.north - p.lat) / acc.deg);
  if (ix < 0 || iy < 0 || ix >= W || iy >= H) continue;
  let land = 0, cov = 0;
  for (let y = Math.max(0, iy - R); y <= Math.min(H - 1, iy + R); y++) for (let x = Math.max(0, ix - R); x <= Math.min(W - 1, ix + R); x++) {
    const o = (y * W + x) * ch, r = data[o], b = data[o + 2];
    if (r === 255) continue; // river or sea
    land++; if (!((b >> 5) & 1)) cov++;
  }
  const centre = (iy * W + ix) * ch;
  const centreCovered = !((data[centre + 2] >> 5) & 1);
  if (land >= 20 && cov / land >= 0.6 && (centreCovered || data[centre] === 255)) out.push(p.slug);
}
const body = `// GENERATED by scripts/flood3d/town-coverage.mjs from public/flood3d/level.webp (towns inside the calibrated area). Do not edit by hand.
export const FLOOD3D_TOWNS: ReadonlySet<string> = new Set(${JSON.stringify(out, null, 1).replace(/\n\s*/g, " ").replace("[ ", "[").replace(" ]", "]")});
`;
writeFileSync("lib/flood3dCoverage.ts", body);
console.log(out.length, "towns:", out.join(", "));
