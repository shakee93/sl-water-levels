const DICTS: Record<Locale, Record<ForecastKpiKey, string>> = { en, si, ta };

export function fkT(lang: Locale) {
  const d = DICTS[lang];
  return (key: ForecastKpiKey, vars?: Record<string, string | number>) => {
    const s = d[key] ?? en[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}

/** A version's name / sentence in this language; a version added later without a translation shows the text from lib/model/versions.json. */
export function versionText(lang: Locale, id: string, field: "name" | "what", fallback: string): string {
  const k = `ver.${id}.${field}` as ForecastKpiKey;
  return DICTS[lang][k] ?? en[k] ?? fallback;
}
