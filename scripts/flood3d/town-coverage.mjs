#!/usr/bin/env node
// Which town pages get the embedded flood test map: towns whose point sits inside the calibrated picture (public/flood3d/level.webp),
// i.e. where the surrounding ground is not flagged "not covered" (blue channel bit 32) and is not just river. Writes lib/flood3dCoverage.ts.
// Re-run after prep.py rewrites level.webp or lib/places.ts changes:  node scripts/flood3d/town-coverage.mjs
// ("sharp" comes with Next.js; nothing is added to package.json.)
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const sharp = require("sharp");
const acc = JSON.parse(readFileSync("public/flood3d/accuracy.json", "utf8")).png;
const { data, info } = await sharp("public/flood3d/level.webp").ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const W = info.width, H = info.height, ch = info.channels;
// places: read the table the same way the site does (lib/places.ts is TypeScript, so strip it with Node's type stripping)
const { PLACES } = await import("../../lib/places.ts");
const R = 5; // +-5 cells (about 150 m)
const out = [];
// Per town, for the sentence above the map ("low ground near X starts to take river water at about N ft"): the ground within 1 km that is calibrated
// and not "usually wet" (those cells are never drawn as flood), as the Nagalagam level at which the 20th-lowest cell (about 1.8 ha, so a street and not a
// single pixel) goes under water, and the share of that ground under water at 2.0, 2.5 ... 9.0 ft. Written to lib/flood3dTownLevels.ts.
const levels = {};
const STEPS = Array.from({ length: 15 }, (_, k) => 2 + k * 0.5);
const R1 = 1000, RC = Math.ceil(R1 / 30);
function townLevels(p, ix, iy) {
  const Ls = [];
  for (let y = Math.max(0, iy - RC); y <= Math.min(H - 1, iy + RC); y++) for (let x = Math.max(0, ix - RC); x <= Math.min(W - 1, ix + RC); x++) {
    const dx = (x - ix) * acc.deg * 111320 * Math.cos((p.lat * Math.PI) / 180), dy = (y - iy) * acc.deg * 110574;
    if (Math.hypot(dx, dy) > R1) continue;
    const o = (y * W + x) * ch, r = data[o], b = data[o + 2];
    if (r === 255 || r === 0 || ((b >> 5) & 1) || ((b >> 6) & 1)) continue;
    Ls.push((r - 1) / 10 + 2);
  }
  if (Ls.length < 150) return null; // too little calibrated ground near the town to say anything
  Ls.sort((a, b) => a - b);
  return { first: Math.round(Ls[19] * 10) / 10, pct: STEPS.map((s) => Math.round((100 * Ls.filter((l) => l <= s).length) / Ls.length)) };
}
for (const p of PLACES) {
  const ix = Math.floor((p.lon - acc.west) / acc.deg), iy = Math.floor((acc.north - p.lat) / acc.deg);
  if (ix < 0 || iy < 0 || ix >= W || iy >= H) continue;
  let land = 0, cov = 0;
  for (let y = Math.max(0, iy - R); y <= Math.min(H - 1, iy + R); y++) for (let x = Math.max(0, ix - R); x <= Math.min(W - 1, ix + R); x++) {
    const o = (y * W + x) * ch, r = data[o], b = data[o + 2];
    if (r === 255) continue; // river or sea
    land++; if (!((b >> 5) & 1)) cov++;
  }
  const centre = (iy * W + ix) * ch;
  const centreCovered = !((data[centre + 2] >> 5) & 1);
  if (land >= 20 && cov / land >= 0.6 && (centreCovered || data[centre] === 255)) { out.push(p.slug); const t = townLevels(p, ix, iy); if (t) levels[p.slug] = t; }
}
const body = `// GENERATED by scripts/flood3d/town-coverage.mjs from public/flood3d/level.webp (towns inside the calibrated area). Do not edit by hand.
export const FLOOD3D_TOWNS: ReadonlySet<string> = new Set(${JSON.stringify(out, null, 1).replace(/\n\s*/g, " ").replace("[ ", "[").replace(" ]", "]")});
`;
writeFileSync("lib/flood3dCoverage.ts", body);
console.log(out.length, "towns:", out.join(", "));
const lv = `// GENERATED by scripts/flood3d/town-coverage.mjs from public/flood3d/level.webp. Do not edit by hand.
// Per covered town, within 1 km: \`first\` = Nagalagam ft at which the first streets (20 grid cells) go under water; \`pct\` = share (%) of the calibrated
// ground under water at 2.0, 2.5 ... 9.0 ft. An illustration of river flooding, never an official level.
export type TownLevels = { first: number; pct: number[] };
export const TOWN_LEVELS_FROM = 2, TOWN_LEVELS_STEP = 0.5;
export const FLOOD3D_TOWN_LEVELS: Record<string, TownLevels> = ${JSON.stringify(levels).replace(/\},/g, "},\n")};
`;
writeFileSync("lib/flood3dTownLevels.ts", lv);
console.log(Object.keys(levels).length, "towns with levels");
