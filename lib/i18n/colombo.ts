const DICTS: Record<Locale, D> = { en: en as unknown as D, si, ta };
export type CC = (key: CKey, vars?: Record<string, string | number>) => string;
export function ccFor(lang: Locale): CC {
  const d = DICTS[lang];
  return (key, vars) => {
    const s = d[key] ?? (en as unknown as D)[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
  };
}
